test('recuperar pedido da lixeira restaura vínculo e data, mesmo com cadastro excluído',async()=>{
 const trash=load('lib/trash-db.js',{'./store':{_pg:{pool}}})
 await trash.ensureSchema(pool)
 await pg.exec('CREATE TABLE app_agenda_orders_v2(id text,company_id text,source_quote_id text)')
 const c=await db.save('trash-crm',null,body('Cliente lixeira'))
 const q=await quotes.createQuote('trash-crm',quote(c.id,'pedido',{data_pedido:'2026-05-10'}))
 const client=await pool.connect();await client.query('BEGIN')
 await trash.archiveQuote(client,'trash-crm',q.id,'source_quote_id')
 await client.query('DELETE FROM app_quotes_v2 WHERE company_id=$1 AND id=$2',['trash-crm',q.id]);await client.query('COMMIT')
 await db.remove('trash-crm',c.id)
 const item=(await pg.query("SELECT id FROM app_trash_v1 WHERE company_id='trash-crm'")).rows[0]
 await trash.transaction(pool,client=>trash.restore(client,'trash-crm',item.id))
 const rank=(await db.ranking('trash-crm')).items[0];assert.equal(rank.last_purchase,'2026-05-10');assert.equal(rank.active,false);assert.equal(rank.purchases,1)
})
